-- 只做一件事：往 site_settings 里补上「星空图」的开关。
--
-- 为什么还是 site_settings 而不是新表：
--   它就是一个"一行一个布尔"的站点配置，和 0012 里的 weather_enabled 同类。
--   后台「站点设置」页是按 key 读写的，加一张表反而要动后台的读写逻辑。
--
-- 为什么默认是 true 而不是 false：
--   星图是**纯本地计算** —— 亮星表和星座连线内嵌在页面包里，
--   月亮和行星的位置用公式现算，一个外部请求都不发。
--   所以"没配过"和"关掉它"应该是两件事，后者要站长明确点一下。
--   环境变量 CELESTIAL_ENABLED 只在**这一行不存在**时兜底
--   （见 src/lib/external/celestial-settings.ts 的优先级说明）。
--
-- 可重复执行：on conflict do nothing —— 你在后台改过的值不会被重跑覆盖。
-- ============================================================================

insert into public.site_settings (key, value)
values
  ('celestial_enabled', 'true'::jsonb)
on conflict (key) do nothing;

